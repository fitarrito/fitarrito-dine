-- Soups & Bowls serving prices. Safe to run more than once.
-- Soup uses protein None. Bowl uses Veg, Chicken, or Prawn.
-- Prawn is shown to customers as Seafood.

CREATE TABLE IF NOT EXISTS public.soups_bowls_price_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dish_title TEXT NOT NULL,
  serving_type TEXT NOT NULL,
  protein TEXT NOT NULL,
  price NUMERIC(10, 2) NOT NULL,
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint AS constraint_row
    JOIN pg_class AS table_row ON table_row.oid = constraint_row.conrelid
    JOIN pg_namespace AS namespace_row ON namespace_row.oid = table_row.relnamespace
    WHERE namespace_row.nspname = 'public'
      AND table_row.relname = 'soups_bowls_price_options'
      AND constraint_row.contype = 'u'
      AND pg_get_constraintdef(constraint_row.oid) ILIKE '%dish_title%'
      AND pg_get_constraintdef(constraint_row.oid) ILIKE '%serving_type%'
      AND pg_get_constraintdef(constraint_row.oid) ILIKE '%protein%'
  ) THEN
    ALTER TABLE public.soups_bowls_price_options
      ADD CONSTRAINT soups_bowls_price_options_dish_serving_protein_key
      UNIQUE (dish_title, serving_type, protein);
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint AS constraint_row
    JOIN pg_class AS table_row ON table_row.oid = constraint_row.conrelid
    JOIN pg_namespace AS namespace_row ON namespace_row.oid = table_row.relnamespace
    WHERE namespace_row.nspname = 'public'
      AND table_row.relname = 'soups_bowls_price_options'
      AND constraint_row.contype = 'c'
      AND pg_get_constraintdef(constraint_row.oid) ILIKE '%serving_type%'
  ) THEN
    ALTER TABLE public.soups_bowls_price_options
      ADD CONSTRAINT soups_bowls_price_options_serving_protein_check
      CHECK (
        (serving_type = 'Soup' AND protein = 'None')
        OR (serving_type = 'Bowl' AND protein IN ('Veg', 'Chicken', 'Prawn'))
      );
  END IF;
END $$;

ALTER TABLE public.soups_bowls_price_options ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'soups_bowls_price_options'
      AND policyname = 'soups_bowls_price_options_public_read'
  ) THEN
    CREATE POLICY soups_bowls_price_options_public_read
      ON public.soups_bowls_price_options
      FOR SELECT
      TO anon, authenticated
      USING (is_available = TRUE);
  END IF;
END $$;

GRANT SELECT ON public.soups_bowls_price_options TO anon, authenticated;

